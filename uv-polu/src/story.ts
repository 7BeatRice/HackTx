export function fallbackStory(ctx: StoryContext): Story {
  const fb = FALLBACKS[ctx.villain]
  const name = ctx.character.name
  const act = ACTIVITY_QUEST[ctx.activity.level]
  const raw = {
    title: fb.title,
    paragraphs: fb.intro(ctx),
    choices: DEFAULT_CHOICES,
    quests: [
      {
        type: 'PROTECTION',
        title: fb.protection.title,
        text: fb.protection.text,
        icon: fb.protection.icon,
        victory: fb.protection.victory(name),
      },
      {
        type: 'ACTIVITY',
        title: act.title,
        text: `Enjoy ${ctx.activity.ideas[0] ?? 'a gentle walk'} for about 20 minutes.`,
        icon: act.icon,
        victory: act.victory(name),
      },
      {
        type: 'WELLNESS',
        title: 'The Silver Spring',
        text: 'Drink a full glass of water and take five slow, deep breaths.',
        icon: 'droplet',
        victory: `You sipped from the silver spring and felt its cool magic wash through you. ${name} feels refreshed and ready.`,
      },
    ],
  }
  return { ...normalizeStory(raw, ctx), source: 'fallback' }
}
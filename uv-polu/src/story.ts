/* ───────────────────────── types ───────────────────────── */

export type QuestType = 'PROTECTION' | 'ACTIVITY' | 'WELLNESS'
export type Villain = 'uv' | 'storm' | 'heat' | 'cold' | 'haze' | 'none'
export type ActivityLevel = 'great' | 'good' | 'careful' | 'indoors'

export type StoryQuest = {
  id: string
  type: QuestType
  title: string
  text: string
  /** Shown in the pop-up when the quest is completed. */
  victory: string
  xp: number
  icon: IconName
}

export type Story = {
  title: string
  paragraphs: string[]
  choices: string[]
  quests: StoryQuest[]
  /** 'ai' = generated by Muse, 'fallback' = built-in tale used when Muse is unavailable. */
  source: 'ai' | 'fallback'
}

export type StoryContext = {
  /** Unique per character + weather + UV + villain + activity + day. Used for caching and quest ids. */
  key: string
  date: string
  character: { name: string; title: string }
  weather: Weather
  kingdom: string
  /** temp is °C */
  readings: Readings
  villain: Villain
  activity: { level: ActivityLevel; ideas: string[] }
}

/* ───────────────────────── XP & levels ───────────────────────── */

/** XP is set here, never by the AI, so rewards stay fair. */
export const QUEST_XP: Record<QuestType, number> = { PROTECTION: 50, ACTIVITY: 75, WELLNESS: 40 }
export const XP_PER_LEVEL = 100

export function levelFor(xp: number) {
  return { level: Math.floor(xp / XP_PER_LEVEL) + 1, into: xp % XP_PER_LEVEL, size: XP_PER_LEVEL }
}

export function roman(n: number): string {
  const map: [number, string][] = [
    [1000, 'M'], [900, 'CM'], [500, 'D'], [400, 'CD'], [100, 'C'], [90, 'XC'],
    [50, 'L'], [40, 'XL'], [10, 'X'], [9, 'IX'], [5, 'V'], [4, 'IV'], [1, 'I'],
  ]
  let out = ''
  for (const [value, symbol] of map) {
    while (n >= value) {
      out += symbol
      n -= value
    }
  }
  return out
}


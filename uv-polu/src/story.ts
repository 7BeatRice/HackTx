/* ───────────────────────── rules: villain & activity ───────────────────────── */

export function villainFor(weather: Weather, r: Readings): Villain {
  if (r.uv >= 6) return 'uv'
  if (weather === 'winter-storm' || r.precipitation >= 50) return 'storm'
  if (r.temp >= 32) return 'heat'
  if (r.temp <= 4) return 'cold'
  if (r.air < 85) return 'haze'
  return 'none'
}

function ideasFor(level: ActivityLevel, villain: Villain, r: Readings): string[] {
  if (level === 'indoors') {
    return ['a royal dance in the great hall', 'gentle stretches like a waking willow', 'a stair-climbing quest up the castle tower']
  }
  if (level === 'careful') {
    if (villain === 'uv') return ['a stroll along the shady woodland path', 'a short walk in the cool of the morning']
    if (villain === 'heat') return ['a slow stroll beneath the tallest trees', 'a quiet game in the shade']
    if (villain === 'cold') return ['a brisk walk wrapped in your warmest cloak', 'a lively game of tag to warm your toes']
    return ['a gentle walk with plenty of rest stops', 'light stretches by a sunny window']
  }
  const runOk = r.temp >= 5 && r.temp <= 28 && r.precipitation < 30
  const swimOk = r.temp >= 24 && r.precipitation < 30 && r.uv < 8
  const ideas = ['a stroll through the whispering woods']
  if (runOk) ideas.unshift('a brisk run along the enchanted trail')
  if (swimOk) ideas.push('a swim in the shimmering lake (with a grown-up nearby)')
  ideas.push('a bicycle ride along the royal road')
  return ideas
}

export function activityFor(r: Readings, villain: Villain): { level: ActivityLevel; ideas: string[] } {
  const extreme = r.temp >= 35 || r.temp <= -5
  let level: ActivityLevel
  if (villain === 'storm' || extreme) level = 'indoors'
  else if (villain !== 'none') level = 'careful'
  else level = r.temp >= 12 && r.temp <= 28 && r.uv <= 5 && r.precipitation < 30 ? 'great' : 'good'
  return { level, ideas: ideasFor(level, villain, r) }
}

function todayKey() {
  const d = new Date()
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
}

export function buildStoryContext(selected: Character, weather: Weather, readings: Readings): StoryContext {
  const villain = villainFor(weather, readings)
  const activity = activityFor(readings, villain)
  const date = todayKey()
  return {
    key: [selected.name, weather, Math.round(readings.uv), villain, activity.level, date].join('|'),
    date,
    character: { name: selected.name, title: selected.title },
    weather,
    kingdom: weatherCopy[weather].kingdom,
    readings,
    villain,
    activity,
  }
}

/* ───────────────────────── validate what the AI sends back ───────────────────────── */

const ICONS: IconName[] = ['sun', 'droplet', 'leaf', 'wind', 'sword', 'trophy']
const TYPES: QuestType[] = ['PROTECTION', 'ACTIVITY', 'WELLNESS']
const DEFAULT_CHOICES = ['Follow the illuminated trail', 'Ask Milo to scout ahead']

const str = (v: unknown, max: number): string | null =>
  typeof v === 'string' && v.trim() ? v.trim().slice(0, max) : null

export function normalizeStory(raw: any, ctx: StoryContext): Story {
  const title = str(raw?.title, 80)
  const paragraphs: string[] = (Array.isArray(raw?.paragraphs) ? raw.paragraphs : [])
    .map((p: unknown) => str(p, 800))
    .filter((p: string | null): p is string => p !== null)
    .slice(0, 3)

  const quests: StoryQuest[] = (Array.isArray(raw?.quests) ? raw.quests : [])
    .slice(0, 3)
    .map((q: any, i: number): StoryQuest | null => {
      const qTitle = str(q?.title, 60)
      const text = str(q?.text, 240)
      const victory = str(q?.victory, 500)
      if (!qTitle || !text || !victory) return null
      const type: QuestType = TYPES.includes(q?.type) ? q.type : TYPES[i] ?? 'WELLNESS'
      const icon: IconName = ICONS.includes(q?.icon) ? q.icon : 'sun'
      return { id: `${ctx.key}#${i}`, type, title: qTitle, text, victory, xp: QUEST_XP[type], icon }
    })
    .filter((q: StoryQuest | null): q is StoryQuest => q !== null)

  if (!title || paragraphs.length < 2 || quests.length < 2) throw new Error('Story response was incomplete')

  const choices: string[] = (Array.isArray(raw?.choices) ? raw.choices : [])
    .map((c: unknown) => str(c, 60))
    .filter((c: string | null): c is string => c !== null)
    .slice(0, 2)

  return { title, paragraphs, choices: choices.length === 2 ? choices : DEFAULT_CHOICES, quests, source: 'ai' }
}

/* ───────────────────────── calling Muse (through the edge function) ───────────────────────── */

export async function fetchStory(ctx: StoryContext): Promise<Story> {
  const { data, error } = await supabase.functions.invoke('story', {
    body: {
      date: ctx.date,
      character: ctx.character,
      weather: ctx.weather,
      kingdom: ctx.kingdom,
      readings: ctx.readings,
      villain: ctx.villain,
      activity: ctx.activity,
    },
  })
  if (error) {
    // Surface the function's real response body in the console while debugging.
    const detail = await (error as any).context?.text?.().catch(() => undefined)
    console.warn('[story] edge function error:', detail ?? error)
    throw error
  }
  return normalizeStory(data, ctx)
}

